def main():
    path = os.path.join(CSV, '2D Visual Clues.csv')
    rows = list(csv.reader(open(path, encoding='utf-8-sig')))
    head = rows[0]
    col = {h.lstrip('\ufeff'): i for i, h in enumerate(head)}
    ac = list(csv.reader(open(os.path.join(CSV, 'All Countries.csv'), encoding='utf-8-sig')))
    dcol = [h.lstrip('\ufeff') for h in ac[0]].index('Domain')
    by_dom = {r[dcol].strip().lstrip('.').upper(): r[0] for r in ac[1:] if r and r[0]}
    by_dom.setdefault('GB', by_dom.get('UK'))
    idx = {r[0]: i for i, r in enumerate(rows) if i and r}
    n = 0
    for table, (cs, ct) in ((BO, ('Bollards 2D', 'Bollards 2D Insight')), (PO, ('Utility Poles 2D', 'Utility Poles 2D Insight'))):
        for code, (spec, text, _short) in table.items():
            name = by_dom[code]
            r = rows[idx[name]]
            r[col[cs]], r[col[ct]] = spec, text
            n += 1
    # legend: clear the three legend columns, then write LEGEND from the top, keeping the "How it works" block after it
    L1, L2, L3 = col['Spec legend'], col['Setting'], col['Allowed values']
    tail = []
    seen = False
    for r in rows[1:]:
        if r[L1] == 'How it works': seen = True
        if seen and (r[L1] or r[L2] or r[L3]): tail.append((r[L1], r[L2], r[L3]))
    old_road_plate = []
    keep = False
    for r in rows[1:]:
        if r[L1] in ('Road Lines & Signs 2D',): keep = True
        if r[L1] == 'How it works': keep = False
        if keep and (r[L1] or r[L2] or r[L3]): old_road_plate.append((r[L1], r[L2], r[L3]))
    for r in rows[1:]: r[L1] = r[L2] = r[L3] = ''
    for i, (a, b, c) in enumerate(LEGEND + old_road_plate + tail):
        rows[1 + i][L1], rows[1 + i][L2], rows[1 + i][L3] = a, b, c
    with open(path, 'w', encoding='utf-8-sig', newline='') as f:
        csv.writer(f).writerows(rows)
    print('cells written for', n, 'country entries')


if __name__ == '__main__':
    main()
